def _wrap(doc: str) -> list[str]:
    return doc.splitlines()


# ----------------------------------------------------------------------------- emit
_PLAIN = re.compile(r"^(?![-?:,\[\]{}#&*!|>'\"%@`])(?!.*: )(?!.* #)(?!.*#$)[^\n]*[^\s]$")
_RESERVED = {"true", "false", "null", "yes", "no", "on", "off", "~", ""}
_NUMBER = re.compile(r"^[-+]?(\d[\d_]*(\.\d*)?|\.\d+)([eE][-+]?\d+)?$|^0x[0-9a-f]+$|^0o[0-7]+$")


def _scalar(v) -> str:
    if isinstance(v, Pinned):
        return f"{_scalar(str(v))} # {v.comment}"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if not isinstance(v, str):
        raise TypeError(f"cannot emit {v!r}")
    if "\n" in v:
        raise ValueError("block scalars are emitted by the caller")
    if v.lower() in _RESERVED or _NUMBER.match(v) or not _PLAIN.match(v) or v != v.strip():
        return "'" + v.replace("'", "''") + "'"
    return v


def emit(doc: dict) -> str:
    out: list[str] = []
    header = doc.pop("_doc", "")
    for line in header.splitlines():
        out.append(f"# {line}".rstrip())
    out.append("")
    _emit_map(doc, 0, out)
    return "\n".join(out).rstrip("\n") + "\n"


def _emit_map(m: dict, indent: int, out: list[str]) -> None:
    pad = " " * indent
    for k, v in m.items():
        if isinstance(k, Commented):
            if out and out[-1] != "":
                out.append("")
            out.append(f"{pad}# {k.comment}")
        key = _scalar(str(k))
        if isinstance(v, dict):
            if not v:
                out.append(f"{pad}{key}: {{}}")
            else:
                out.append(f"{pad}{key}:")
                _emit_map(v, indent + 2, out)
        elif isinstance(v, list):
            if not v:
                out.append(f"{pad}{key}: []")
            else:
                out.append(f"{pad}{key}:")
                _emit_list(v, indent + 2, out)
        elif isinstance(v, str) and "\n" in v:
            out.append(f"{pad}{key}: |")
            for line in v.rstrip("\n").splitlines():
                out.append(f"{pad}  {line}" if line else "")
        else:
            out.append(f"{pad}{key}: {_scalar(v)}")


def _emit_list(items: list, indent: int, out: list[str]) -> None:
    pad = " " * indent
    for item in items:
        if isinstance(item, dict):
            first = True
            sub: list[str] = []
            _emit_map(item, indent + 2, sub)
            for line in sub:
                if first:
                    out.append(f"{pad}- {line[indent + 2:]}")
                    first = False
                else:
                    out.append(line)
        elif isinstance(item, list):
            raise TypeError("nested lists are not emitted")
        elif isinstance(item, str) and "\n" in item:
            raise TypeError("block scalars in lists are not emitted")
        else:
            out.append(f"{pad}- {_scalar(item)}")


