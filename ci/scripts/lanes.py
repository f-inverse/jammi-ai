#!/usr/bin/env python3
"""The lanes CI runs, as one typed table: `ci/lanes.toml`, rendered into every
workflow under `.github/workflows/` and the maintainer page that describes
them.

    python3 ci/scripts/lanes.py render          # write the workflows and the page
    python3 ci/scripts/lanes.py check           # they are what the table renders
    python3 ci/scripts/lanes.py list [WORKFLOW] # the lanes, by workflow
    python3 ci/scripts/lanes.py run LANE        # a lane's commands, here, in order
    python3 ci/scripts/lanes.py --self-test

A lane is a command with four typed properties: the host it runs on, what it
needs of that host, when it runs, and what it produces or consumes. Every
property GitHub spells per job -- `runs-on`, `container`, `services`,
`needs`, `if`, `permissions`, the checkout, the toolchain, the artifact
uploads and downloads, the release gate, the summary -- is derived from those
four here, once, so the workflows carry no logic of their own and a state the
table cannot express cannot reach a workflow: a paid lane on a pull request,
a publisher off a tag, a secret a lane never declared, an artifact nothing
builds, a feature spelled where the manifest should be read.

The rendered files are committed, because GitHub reads YAML; `check` holds
them equal to what the table renders, and `render` rewrites them. A lane's
`why` is the one sentence above its job; the architecture is the page.
"""

