class TableError(ValueError):
    """The table is not what its schema says, or says something CI cannot be."""


def fields(table: dict, where: str, required: set[str], optional: set[str]) -> dict:
    if missing := sorted(required - table.keys()):
        raise TableError(f"{where}: missing {missing}")
    if unknown := sorted(table.keys() - required - optional):
        raise TableError(f"{where}: unknown {unknown} (allowed: {sorted(required | optional)})")
    return table


@dataclass(frozen=True)
class Trigger:
    kind: str  # pr | main | nightly | dispatch | label | tag
    value: str = ""  # the label name, the tag prefix

    @staticmethod
    def parse(text: str, where: str) -> "Trigger":
        kind, _, value = text.partition(":")
        if kind in TRIGGER_KINDS and not value:
            return Trigger(kind)
        if kind in ("label", "tag") and value:
            return Trigger(kind, value)
        raise TableError(f"{where}: `{text}` is not a trigger (pr, main, schedule, dispatch, label:<name>, tag:<prefix>)")

    @property
    def text(self) -> str:
        return f"{self.kind}:{self.value}" if self.value else self.kind

    @property
    def predicate(self) -> str:
        return {
            "pr": "github.event_name == 'pull_request'",
            "main": "github.event_name == 'push'",
            "schedule": "github.event_name == 'schedule'",
            "dispatch": "github.event_name == 'workflow_dispatch'",
            "label": f"(github.event_name == 'pull_request' && github.event.label.name == '{self.value}')",
            "tag": f"startsWith(github.ref, 'refs/tags/{self.value}')",
        }[self.kind]


@dataclass(frozen=True)
class Input:
    name: str
    description: str
    type: str
    required: bool
    default: object
    options: tuple[str, ...]


@dataclass(frozen=True)
class Workflow:
    id: str
    file: str
    name: str
    doc: str
    on: tuple[Trigger, ...]
    cron: str
    cancel_superseded: bool
    group: str
    paid_cron: bool
    inputs: tuple[Input, ...]

    @property
    def tag(self) -> Trigger | None:
        tags = [t for t in self.on if t.kind == "tag"]
        return tags[0] if tags else None


@dataclass(frozen=True)
class Artifact:
    name: str
    path: str
    retention: int | None
    if_no_files_found: str
    compression: int | None


@dataclass(frozen=True)
class Step:
    raw: dict

    @property
    def kind(self) -> str:
        for k in ("run", "uses", "upload", "download"):
            if k in self.raw:
                return k
        raise TableError(f"a step is none of run/uses/upload/download: {self.raw}")

    @property
    def text(self) -> str:
        """Every string in the step, for the rules that read step text."""
        return "\n".join(_strings(self.raw))


@dataclass(frozen=True)
class Lane:
    id: str
    why: str
    workflows: tuple[str, ...]
    name: str
    when: tuple[Trigger, ...] | None
    host: str
    arch: str
    rust: object  # False | True | "release" | "no-sccache"
    needs: tuple[str, ...]
    timeout: int | str | None
    after: tuple[str, ...]
    produces: tuple[str, ...]
    consumes: tuple[str, ...]
    env: dict[str, str]
    outputs: dict[str, str]
    checkout: bool
    publishes: str | None
    environment: dict | None
    dir: str | None
    legs: tuple[dict, ...]
    steps: tuple[Step, ...]

    @property
    def text(self) -> str:
        return "\n".join([*(s.text for s in self.steps), *_strings(self.env), *_strings(list(self.legs))])

    def _expand(self, names: tuple[str, ...]) -> tuple[str, ...]:
        """`names`, each `{field}` filled from every leg (an artifact name per leg)."""
        out: list[str] = []
        for name in names:
            if "{" not in name:
                out.append(name)
                continue
            if not self.legs:
                raise TableError(f"lane.{self.id}: `{name}` names a leg field and the lane has no legs")
            for leg in self.legs:
                try:
                    out.append(name.format(**_leg_fields(self, leg)))
                except KeyError as e:
                    raise TableError(f"lane.{self.id}: `{name}` names field {e} that a leg lacks") from None
        return tuple(dict.fromkeys(out))

    @property
    def produced(self) -> tuple[str, ...]:
        return self._expand(self.produces)

    @property
    def consumed(self) -> tuple[str, ...]:
        return self._expand(self.consumes)


@dataclass(frozen=True)
class Table:
    workflows: dict[str, Workflow]
    artifacts: dict[str, Artifact]
    actions: dict[str, str]
    lanes: dict[str, Lane]

    def producer(self, artifact: str) -> Lane:
        for lane in self.lanes.values():
            if artifact in lane.produced:
                return lane
        raise TableError(f"artifact `{artifact}` is produced by no lane")

    def in_workflow(self, workflow: str) -> list[Lane]:
        return [lane for lane in self.lanes.values() if workflow in lane.workflows]


def _leg_fields(lane: "Lane", leg: dict) -> dict:
    """A leg's fields with the ones the renderer derives: `target` and
    `platform` from `arch`."""
    out = {k: v for k, v in leg.items() if k != "host"}
    arch = leg.get("arch", lane.arch)
    if "arch" in leg:
        out.setdefault("target", TARGETS[arch])
        out.setdefault("platform", f"linux/{arch}")
    return out


def _strings(node) -> list[str]:
    if isinstance(node, dict):
        return [s for v in node.values() for s in _strings(v)]
    if isinstance(node, list):
        return [s for v in node for s in _strings(v)]
    return [node] if isinstance(node, str) else []


# ----------------------------------------------------------------------------- parse
def parse(text: str, root: Path | None = None) -> Table:
    """The table `text` describes; with `root`, the rules that read what a
    step runs also read the scripts it names, transitively."""
    doc = tomllib.loads(text)
    fields(doc, "top level", {"workflow", "artifact", "action", "lane"}, set())
    workflows = {wid: _parse_workflow(wid, t) for wid, t in doc["workflow"].items()}
    artifacts = {
        name: Artifact(
            name,
            **{
                k.replace("-", "_"): v
                for k, v in {
                    "retention": None,
                    "if-no-files-found": "error",
                    "compression": None,
                    **fields(t, f"artifact.{name}", {"path"}, {"retention", "if-no-files-found", "compression"}),
                }.items()
            },
        )
        for name, t in doc["artifact"].items()
    }
    actions = doc["action"]
    for alias, ref in actions.items():
        if not isinstance(ref, str) or not re.fullmatch(r"[\w.-]+/[\w.-]+@[0-9a-f]{40} # .+", ref):
            raise TableError(f"action.{alias}: not `owner/repo@<40-hex sha> # <version>`: {ref!r}")
    lanes = {lid: _parse_lane(lid, t, workflows) for lid, t in doc["lane"].items()}
    table = Table(workflows, artifacts, actions, lanes)
    for finding in validate(table, root):
        raise TableError(finding)
    return table


def _parse_workflow(wid: str, t: dict) -> Workflow:
    where = f"workflow.{wid}"
    fields(t, where, {"name", "doc", "on"}, {"file", "cron", "cancel-superseded", "group", "paid-cron", "inputs"})
    on = tuple(Trigger.parse(x, where) for x in t["on"])
    if ("schedule" in [x.kind for x in on]) != ("cron" in t):
        raise TableError(f"{where}: `cron` exactly when `on` carries schedule")
    if sum(x.kind == "tag" for x in on) > 1:
        raise TableError(f"{where}: one tag family per workflow")
    inputs = []
    for name, it in t.get("inputs", {}).items():
        fields(it, f"{where}.inputs.{name}", {"description", "type"}, {"required", "default", "options"})
        inputs.append(Input(name, it["description"], it["type"], it.get("required", False), it.get("default"), tuple(it.get("options", ()))))
    if inputs and "dispatch" not in [x.kind for x in on]:
        raise TableError(f"{where}: inputs without a dispatch trigger")
    return Workflow(
        wid,
        t.get("file", f"{wid}.yml"),
        t["name"],
        t["doc"].strip(),
        on,
        t.get("cron", ""),
        t.get("cancel-superseded", False),
        t.get("group", f"{wid}-${{{{ github.ref }}}}"),
        t.get("paid-cron", False),
        tuple(inputs),
    )


def _parse_lane(lid: str, t: dict, workflows: dict[str, Workflow]) -> Lane:
    where = f"lane.{lid}"
    fields(
        t,
        where,
        {"why", "steps"},
        {"workflow", "name", "when", "host", "arch", "rust", "needs", "timeout", "after", "produces", "consumes", "env", "outputs", "checkout", "publishes", "environment", "dir", "legs"},
    )
    wf = t.get("workflow", "ci")
    wfs = tuple([wf] if isinstance(wf, str) else wf)
    for w in wfs:
        if w not in workflows:
            raise TableError(f"{where}: unknown workflow `{w}`")
    when = None
    if "when" in t:
        when = tuple(Trigger.parse(x, where) for x in t["when"])
        every = {x for w in wfs for x in workflows[w].on}
        if not set(when) <= every:
            raise TableError(f"{where}: `when` names a trigger its workflows lack ({[x.text for x in when]} vs {sorted(x.text for x in every)})")
        for w in wfs:
            if not set(when) & set(workflows[w].on):
                raise TableError(f"{where}: `when` leaves it nothing to run on in `{w}`")
    host = t.get("host", "cpu-image")
    if host not in HOSTS:
        raise TableError(f"{where}: host `{host}` is none of {HOSTS}")
    arch = t.get("arch", "amd64")
    if arch not in RUNNERS:
        raise TableError(f"{where}: arch `{arch}` is none of {sorted(RUNNERS)}")
    rust = t.get("rust", False)
    if rust is not False and rust not in RUST:
        raise TableError(f"{where}: rust is true, \"release\" or \"no-sccache\"")
    needs = tuple(t.get("needs", ()))
    for n in needs:
        if n not in NEEDS:
            raise TableError(f"{where}: unknown need `{n}` (needs: {NEEDS})")
    publishes = t.get("publishes")
    if publishes is not None and publishes not in PUBLISHES:
        raise TableError(f"{where}: publishes is one of {PUBLISHES}")
    legs = tuple(t.get("legs", ()))
    for leg in legs:
        if "host" in leg and leg["host"] not in HOSTS:
            raise TableError(f"{where}: a leg's host `{leg['host']}` is none of {HOSTS}")
        if "arch" in leg and leg["arch"] not in RUNNERS:
            raise TableError(f"{where}: a leg's arch `{leg['arch']}` is none of {sorted(RUNNERS)}")
    steps = tuple(Step(s) for s in t["steps"])
    # An explicit upload step produces its artifact as surely as `produces` does.
    produces = tuple(dict.fromkeys([*t.get("produces", ()), *(s.raw["upload"] for s in steps if "upload" in s.raw)]))
    for s in steps:
        fields(s.raw, f"{where}.steps", set(), {"name", "run", "uses", "with", "env", "if", "when", "id", "dir", "shell", "upload", "download", "path", "from"})
        if s.kind == "download" and "path" not in s.raw:
            raise TableError(f"{where}.steps: a download names its path")
        s.kind
    return Lane(
        lid,
        t["why"].strip(),
        wfs,
        t.get("name", lid),
        when,
        host,
        arch,
        rust,
        needs,
        t.get("timeout"),
        tuple(t.get("after", ())),
        produces,
        tuple(t.get("consumes", ())),
        dict(t.get("env", {})),
        dict(t.get("outputs", {})),
        t.get("checkout", True),
        publishes,
        t.get("environment"),
        t.get("dir"),
        legs,
        steps,
    )


# ----------------------------------------------------------------------------- validate
def validate(table: Table, root: Path | None = None) -> list[str]:
    """What the table says that CI cannot be. Every rule is a shape a hand-written
    workflow could take and a reviewer could miss."""
    out: list[str] = []
    for lane in table.lanes.values():
        w = f"lane.{lane.id}"
        wfs = [table.workflows[x] for x in lane.workflows]
        text = lane.text
        if root is not None:
            text, missing = _with_scripts(text, root)
            out += [f"{w}: names `{m}`, which does not exist" for m in missing]
        if not lane.why.endswith("."):
            out.append(f"{w}: `why` is a sentence")
        if "${{ secrets." in text:
            out.append(f"{w}: reads a secret outside a need (hub-token, runpod)")
        try:
            edges = _edges(table, lane, wfs[0])
        except TableError as e:
            out.append(str(e))
            edges = set()
        for ref in set(NEEDS_REF.findall(text)):
            if ref not in edges and ref != PROOF_LANE:
                out.append(f"{w}: `needs.{ref}` is not an edge of this lane (after, consumes, proof)")
        if lane.publishes == "release":
            if not all(wf.tag and _when(lane, wf) == (wf.tag,) for wf in wfs):
                out.append(f"{w}: a release lane runs when its workflow's tag is pushed and never else (`when = [\"tag:...\"]`)")
            if any(c in text for c in COMPILES):
                out.append(f"{w}: a release lane compiles nothing; it promotes what the proving run built")
        elif any(p in text for p in PUBLISH_PRIMITIVES):
            if lane.publishes is None:
                out.append(f"{w}: publishes (its steps carry a publish primitive) but declares no `publishes`")
            elif any(t.kind not in ("main", "pr") for wf in wfs for t in wf.on):
                out.append(f"{w}: a `{lane.publishes}` promotion is a merge-path lane, never a release")
        if "runpod" in lane.needs:
            for wf in wfs:
                bad = [t.text for t in wf.on if t.kind in ("pr", "main", "tag") or (t.kind == "schedule" and not wf.paid_cron)]
                if bad:
                    out.append(f"{w}: rents hardware, so `{wf.id}` may fire only by label, dispatch or a reviewed schedule (`paid-cron = true`), not {bad}")
        if any(b in text for b in WHEEL_BUILDS) and WHEEL_GATE not in text:
            out.append(f"{w}: builds a wheel and never holds it to PyPI's per-file limit ({WHEEL_GATE})")
        if lane.rust == "release":
            for m in FEATURE_FLAG.finditer(text):
                if "$" not in m.group(1):
                    out.append(f"{w}: a release build spells features ({m.group(0).strip()!r}); it reads ci/release-feature-manifest.json")
        if "python" in lane.needs and lane.host not in BARE_HOSTS and not any(l.get("host") in BARE_HOSTS for l in lane.legs):
            out.append(f"{w}: the CI image carries Python; `python` is for a bare host")
        if "maturin" in lane.needs and "python" not in lane.needs:
            out.append(f"{w}: maturin on a bare host installs into the interpreter `python` provides; name both")
        if lane.host == "cuda-image" and lane.arch != "amd64":
            out.append(f"{w}: the CUDA image is amd64 only")
        if "s3" in lane.needs and "postgres" not in lane.needs:
            out.append(f"{w}: the S3-class store lane also needs postgres (the harness refuses a missing backend)")
        for a in lane.produces:
            if a not in table.artifacts:
                out.append(f"{w}: produces `{a}`, which `artifact` does not define")
        try:
            for a in lane.consumed:
                table.producer(a)
            for step in lane.steps:
                if step.kind == "download" and "from" in step.raw and step.raw["from"] not in table.workflows:
                    out.append(f"{w}: a download `from` an unknown workflow `{step.raw['from']}`")
        except TableError as e:
            out.append(f"{w}: {e}")
        for a in lane.after:
            if a not in table.lanes and a not in (PROOF_LANE, AWAIT_LANE):
                out.append(f"{w}: after `{a}`, which is no lane")
        if lane.publishes == "ci-image" and not lane.name.startswith(ci_image.BUILDER_JOB_PREFIX):
            out.append(f"{w}: a CI image builder is named `{ci_image.BUILDER_JOB_PREFIX}...` so every other workflow's wait sees its failure")
        if lane.environment is not None and lane.publishes != "release":
            out.append(f"{w}: a deployment environment belongs to a release lane")
    for name, art in table.artifacts.items():
        if not any(name in lane.produces for lane in table.lanes.values()):
            out.append(f"artifact.{name}: no lane produces it")
    for wf in table.workflows.values():
        lanes = table.in_workflow(wf.id)
        if not lanes:
            out.append(f"workflow.{wf.id}: no lane runs in it")
        if any(l.publishes == "release" for l in lanes) and wf.tag is None:
            out.append(f"workflow.{wf.id}: a release lane needs a tag trigger")
    return out


def _with_scripts(text: str, root: Path) -> tuple[str, list[str]]:
    """`text` with every `ci/scripts/*.sh` it names appended, comments dropped,
    transitively; and the scripts it names that do not exist."""
    seen: set[str] = set()
    missing: list[str] = []
    pending = SCRIPT_REF.findall(text)
    parts = [text]
    while pending:
        rel = pending.pop()
        if rel in seen:
            continue
        seen.add(rel)
        path = root / rel
        if not path.is_file():
            missing.append(rel)
            continue
        body = "\n".join(l for l in path.read_text().splitlines() if not l.lstrip().startswith("#"))
        parts.append(body)
        pending += SCRIPT_REF.findall(body)
    return "\n".join(parts), sorted(missing)


def _edges(table: Table, lane: Lane, wf: Workflow) -> set[str]:
    """The job ids `lane` may name in `needs.<id>` within `wf`."""
    edges = set(lane.after)
    producers = {table.producer(a).id for a in lane.consumed}
    local = {p for p in producers if wf.id in table.lanes[p].workflows}
    if local and local != producers:
        raise TableError(f"lane.{lane.id}: consumes from this workflow and from another at once")
    edges |= local
    if producers and not local:
        edges |= {_resolver_id(w) for w in _remote_workflows(table, lane)}
    return edges


def _remote_workflows(table: Table, lane: Lane) -> list[str]:
    """The workflows, in table order, whose runs hold what `lane` consumes."""
    return sorted({table.producer(a).workflows[0] for a in lane.consumed}, key=list(table.workflows).index)


def _resolver_id(workflow: str) -> str:
    return f"artifacts-{workflow}"


# ----------------------------------------------------------------------------- render
class Commented(str):
    """A mapping key rendered with a comment line above it."""

    comment: str

    def __new__(cls, key: str, comment: str):
        self = super().__new__(cls, key)
        self.comment = comment
        return self


class Pinned(str):
    """A scalar rendered with a trailing comment: an action reference and the
    version its sha pins, `owner/repo@<sha> # vX`."""

    comment: str

    def __new__(cls, ref: str):
        value, _, comment = ref.partition(" # ")
        self = super().__new__(cls, value)
        self.comment = comment
        return self


def render_all(table: Table, refs: dict[str, str]) -> dict[str, str]:
    """`{repo-relative path: text}` for every rendered file."""
    out = {str(WORKFLOWS_DIR / wf.file): emit(render_workflow(table, wf, refs)) for wf in table.workflows.values()}
    out[str(PAGE)] = render_page(table)
    return out


def render_workflow(table: Table, wf: Workflow, refs: dict[str, str]) -> dict:
    lanes = table.in_workflow(wf.id)
    jobs: dict = {}
    needs_await = wf.id != "ci" and any(_uses_image(l) for l in lanes)
    if needs_await:
        jobs[Commented(AWAIT_LANE, "The tree's CI images, built by ci.yml's run for the same commit.")] = _await_job(table)
    if any(l.publishes == "release" for l in lanes):
        jobs[Commented(PROOF_LANE, "The release gate: the tree's recorded verdicts, and the tag names its version.")] = _proof_job(table, wf)
    local = {x.id for x in lanes}
    for other in sorted({w for l in lanes if _consumes_other_run(table, l, wf) for w in _remote_workflows(table, l)}, key=list(table.workflows).index):
        names = sorted({a for l in lanes for a in l.consumed if table.producer(a).id not in local and table.producer(a).workflows[0] == other})
        jobs[Commented(_resolver_id(other), f"The {other}.yml run that proved this tree, which holds what this workflow installs.")] = _resolver_job(table, other, names)
    for lane in lanes:
        jobs[Commented(lane.id, lane.why)] = render_job(table, wf, lane, refs, needs_await)
    if any(t.kind == "pr" for t in wf.on):
        jobs[Commented(SUMMARY_LANE, "The one check a ruleset requires: every job above succeeded or was skipped by its trigger.")] = _summary_job(list(jobs))
    doc: dict = {"name": wf.name, "on": _on(wf)}
    if wf.cancel_superseded:
        doc["concurrency"] = {"group": wf.group, "cancel-in-progress": "${{ github.ref != 'refs/heads/main' }}"}
    elif not any(l.needs and "runpod" in l.needs for l in lanes):
        doc["concurrency"] = {"group": wf.group, "cancel-in-progress": False}
    doc["permissions"] = {"contents": "read"}
    doc["jobs"] = jobs
    return {"_doc": f"{GENERATED}\n\n{wf.doc}", **doc}


def _uses_image(lane: Lane) -> bool:
    return lane.host in IMAGE_HOSTS or any(l.get("host") in IMAGE_HOSTS for l in lane.legs) or "{image:" in lane.text


def _on(wf: Workflow) -> dict:
    on: dict = {}
    kinds = {t.kind: t for t in wf.on}
    if "main" in kinds:
        on["push"] = {"branches": ["main"]}
    if "tag" in kinds:
        on["push"] = {"tags": [f"{kinds['tag'].value}*"]}
    if "pr" in kinds:
        on["pull_request"] = {}
    if "label" in kinds:
        on["pull_request"] = {"types": ["labeled"]}
    if "schedule" in kinds:
        on["schedule"] = [{"cron": wf.cron}]
    if "dispatch" in kinds:
        on["workflow_dispatch"] = {"inputs": {i.name: _input(i) for i in wf.inputs}} if wf.inputs else {}
    return on


def _input(i: Input) -> dict:
    d: dict = {"description": i.description, "required": i.required, "type": i.type}
    if i.default is not None:
        d["default"] = i.default
    if i.options:
        d["options"] = list(i.options)
    return d


def _action(table: Table, alias: str) -> Pinned:
    return Pinned(table.actions[alias])


def _checkout(table: Table, fetch_depth: int | None = None, submodules: bool | None = None) -> dict:
    step: dict = {"uses": _action(table, "checkout")}
    with_ = {}
    if fetch_depth is not None:
        with_["fetch-depth"] = fetch_depth
    if submodules is not None:
        with_["submodules"] = submodules
    if with_:
        step["with"] = with_
    return step


