def render_job(table: Table, wf: Workflow, lane: Lane, refs: dict[str, str], has_await: bool) -> dict:
    job: dict = {}
    if lane.name != lane.id:
        job["name"] = _template(lane.name)
    needs = sorted(_edges(table, lane, wf))
    if lane.publishes == "release":
        needs.append(PROOF_LANE)
    if wf.id == "ci":
        for image, builder in (("cpu-image", "image-cpu-merge"), ("cuda-image", "image-cuda-merge")):
            if (lane.host == image or any(l.get("host") == image for l in lane.legs)) and lane.id != builder:
                needs.append(builder)
    elif has_await and lane.id != AWAIT_LANE and _uses_image(lane):
        needs.append(AWAIT_LANE)
    if needs:
        job["needs"] = sorted(set(needs))
    when = _when(lane, wf)
    if set(when) != set(wf.on) or any(t.kind == "label" for t in wf.on):
        job["if"] = " || ".join(t.predicate for t in when)
    hosts = {leg.get("host", lane.host) for leg in lane.legs} | {lane.host}
    mixed = len(hosts) > 1 or len({leg.get("arch", lane.arch) for leg in lane.legs}) > 1
    if mixed:
        job["runs-on"] = "${{ matrix.runner }}"
        if any(_container(h, refs) for h in hosts):
            job["container"] = "${{ matrix.container }}"
    else:
        job["runs-on"] = _runner(lane.host, lane.arch)
        container = _container(lane.host, refs)
        if container:
            job["container"] = container
    if lane.environment:
        job["environment"] = lane.environment
    perms = {"contents": "read"}
    for n in lane.needs:
        perms.update(PERMISSION_NEEDS.get(n, {}))
    if _consumes_other_run(table, lane, wf) or lane.publishes == "release":
        perms["actions"] = "read"
    if perms != {"contents": "read"}:
        job["permissions"] = perms
    if "runpod" in lane.needs:
        job["concurrency"] = {"group": f"{lane.id}-${{{{ github.ref }}}}", "cancel-in-progress": False}
    if lane.timeout:
        job["timeout-minutes"] = lane.timeout
    if lane.legs:
        job["strategy"] = {"fail-fast": False, "matrix": {"include": [_leg(lane, leg, refs, mixed, "container" in job, len(hosts & set(BARE_HOSTS)) not in (0, len(hosts))) for leg in lane.legs]}}
    if "postgres" in lane.needs:
        job["services"] = {
            "postgres": {
                "image": refs["postgres"],
                "env": {"POSTGRES_USER": PG_USER, "POSTGRES_PASSWORD": PG_PASSWORD, "POSTGRES_DB": PG_DB},
                "options": f'--health-cmd "pg_isready -U {PG_USER} -d {PG_DB}" --health-interval 5s --health-timeout 5s --health-retries 12',
                "ports": ["5432:5432"],
            }
        }
    env: dict = {}
    if lane.rust:
        env.update({"CARGO_TERM_COLOR": "always", "RUST_BACKTRACE": "1"})
    if "postgres" in lane.needs:
        env["JAMMI_TEST_PG_URL"] = PG_URL
    if "hub-token" in lane.needs:
        env["HF_TOKEN"] = "${{ secrets.HF_TOKEN }}"
    if "runpod" in lane.needs:
        env.update({"RUNPOD_API_KEY": "${{ secrets.RUNPOD_API_KEY }}", "GIT_REPO": "https://github.com/${{ github.repository }}.git"})
    if lane.consumes:
        if not _consumes_other_run(table, lane, wf):
            env[ARTIFACT_RUN_ENV] = "${{ github.run_id }}"
        elif len(remotes := _remote_workflows(table, lane)) == 1:
            env[ARTIFACT_RUN_ENV] = f"${{{{ needs.{_resolver_id(remotes[0])}.outputs.run }}}}"
    env.update({k: _subst(v, refs) for k, v in lane.env.items()})
    if env:
        job["env"] = env
    if lane.outputs:
        job["outputs"] = {k: f"${{{{ {v} }}}}" for k, v in lane.outputs.items()}
    if lane.dir:
        job["defaults"] = {"run": {"working-directory": lane.dir}}
    job["steps"] = _steps(table, lane, refs, mixed)
    return job


def _when(lane: Lane, wf: Workflow) -> tuple[Trigger, ...]:
    """The triggers of `wf` the lane runs on."""
    return tuple(t for t in wf.on if lane.when is None or t in lane.when)


def _consumes_other_run(table: Table, lane: Lane, wf: Workflow) -> bool:
    return bool(lane.consumes) and not any(wf.id in table.lanes[table.producer(a).id].workflows for a in lane.consumed)


def _runner(host: str, arch: str) -> str:
    return MACOS_RUNNER if host == "macos" else RUNNERS[arch]


def _container(host: str, refs: dict[str, str]) -> str | None:
    if host in IMAGE_HOSTS:
        return refs[IMAGE_HOSTS[host]]
    if host == "colab":
        return refs["colab"]
    return None


def _leg(lane: Lane, leg: dict, refs: dict[str, str], mixed: bool, container: bool, mixed_bare: bool) -> dict:
    """A matrix row: the leg's own fields, the ones the renderer derives, and
    only those of `runner`, `container` and `bare` the job reads."""
    host = leg.get("host", lane.host)
    arch = leg.get("arch", lane.arch)
    out = _leg_fields(lane, leg)
    if mixed:
        out["runner"] = _runner(host, arch)
    if container:
        out["container"] = _container(host, refs) or ""
    if mixed_bare:
        out["bare"] = host in BARE_HOSTS
    return out


def _template(name: str) -> str:
    return re.sub(r"\{(\w+)\}", r"${{ matrix.\1 }}", name)


def _subst(text: str, refs: dict[str, str]) -> str:
    def image(m: re.Match) -> str:
        ref = refs[m.group(1)]
        repo, _, tag = ref.partition(":")
        return {"": ref, "-repo": repo, "-tag": tag}[m.group(2) or ""]

    text = re.sub(r"\{image:(\w+)(-repo|-tag)?\}", image, text)
    return text.replace("{artifact-run}", f"${{{{ env.{ARTIFACT_RUN_ENV} }}}}")


def _steps(table: Table, lane: Lane, refs: dict[str, str], mixed: bool) -> list[dict]:
    steps: list[dict] = []
    hosts = {l.get("host", lane.host) for l in lane.legs} | {lane.host}
    bare = bool(hosts & set(BARE_HOSTS))
    bare_if = None if hosts <= set(BARE_HOSTS) or not bare else "${{ matrix.bare }}"
    if lane.checkout:
        steps.append(_checkout(table, 0 if "full-history" in lane.needs else None, False if "cutlass" in lane.needs else None))
    if "cutlass" in lane.needs:
        steps.append({"name": "Init the CUTLASS submodule", "run": "git submodule update --init --depth 1 crates/jammi-kernels/third_party/cutlass"})
    if "nccl" in lane.needs:
        steps.append({"name": "The image carries NCCL (header + link library)", "run": "rpm -q libnccl libnccl-devel && test -e /usr/include/nccl.h && test -e /usr/lib64/libnccl.so"})
    if "python" in lane.needs:
        steps.append(_bare({"uses": _action(table, "setup-python"), "with": {"python-version": PYTHON}}, bare_if))
    if "maturin" in lane.needs:
        # The CI image carries maturin; a bare host takes the pip release of
        # the same version into the interpreter setup-python put on PATH.
        steps.append(_bare({"name": "maturin at its pin", "run": "bash .docker/pinned-tools.sh maturin"}, bare_if))
    if "node" in lane.needs:
        steps.append({"uses": _action(table, "setup-node"), "with": {"node-version-file": "clients/typescript/.nvmrc", "registry-url": "https://registry.npmjs.org"}})
    if lane.rust:
        if bare:
            host_step: dict = {"uses": "./.github/actions/setup-rust-host"}
            if any("rust_target" in l for l in lane.legs):
                host_step["with"] = {"targets": "${{ matrix.rust_target }}"}
            steps.append(_bare(host_step, bare_if))
        ci_step: dict = {"uses": "./.github/actions/setup-rust-ci"}
        if lane.rust == "release":
            ci_step["with"] = {"deny-warnings": "false"}
        elif lane.rust == "no-sccache":
            ci_step["with"] = {"no-sccache": "true"}
        steps.append(ci_step)
    if "kubeconform" in lane.needs:
        if bare:
            steps.append({"name": "kustomize and kubeconform at their pins", "run": "sudo bash .docker/pinned-tools.sh kustomize kubeconform"})
        steps.append({"uses": _action(table, "cache"), "with": {"path": "${{ github.workspace }}/.kubeconform-cache", "key": "kubeconform-schemas-${{ hashFiles('ci/scripts/check_kube_manifests.sh') }}"}})
    if "s3" in lane.needs:
        steps += [
            {"uses": _action(table, "cache"), "with": {"path": "/opt/s3-test-store", "key": "s3-test-store-${{ hashFiles('ci/scripts/s3_test_store.sh') }}"}},
            {"name": "Start the S3-class store", "run": 'export JAMMI_S3_STORE_DIR=/opt/s3-test-store\nci/scripts/s3_test_store.sh start --addr 127.0.0.1:9000 --data /tmp/s3-test-store\nci/scripts/s3_test_store.sh env --addr 127.0.0.1:9000 >> "$GITHUB_ENV"\n'},
            {"name": "Every distributed backend is provisioned (no hollow green)", "run": "bash ci/scripts/require_distributed_backends.sh"},
        ]
    if "audit-key" in lane.needs:
        steps.append({"name": "An ephemeral audit master key for this throwaway stack", "run": 'key="$(openssl rand -hex 32)"\necho "::add-mask::$key"\necho "JAMMI_AUDIT_MASTER_KEY=$key" >> "$GITHUB_ENV"\n'})
    uploaded: set[str] = set()
    for step in lane.steps:
        steps.append(_step(table, lane, step, refs))
        if step.kind == "upload":
            uploaded.add(step.raw["upload"])
    for name in lane.produces:
        if name not in uploaded:
            steps.append(_upload(table, name))
    return steps


def _bare(step: dict, bare_if: str | None) -> dict:
    return {"if": bare_if, **step} if bare_if else step


def _step(table: Table, lane: Lane, step: Step, refs: dict[str, str]) -> dict:
    raw = step.raw
    out: dict = {}
    if "when" in raw:
        out["if"] = Trigger.parse(raw["when"], f"lane.{lane.id}.steps").predicate
    if "if" in raw:
        out["if"] = raw["if"]
    if "name" in raw:
        out["name"] = raw["name"]
    if "id" in raw:
        out["id"] = raw["id"]
    if step.kind == "upload":
        up = _upload(table, raw["upload"])
        return {**out, **up}
    if step.kind == "download":
        run_id = f"${{{{ needs.{_resolver_id(raw['from'])}.outputs.run }}}}" if "from" in raw else f"${{{{ env.{ARTIFACT_RUN_ENV} }}}}"
        return {**out, "uses": _action(table, "download-artifact"), "with": {"name": _template(raw["download"]), "path": _subst(raw["path"], refs), "run-id": run_id, "github-token": "${{ github.token }}"}}
    if step.kind == "uses":
        uses = raw["uses"]
        out["uses"] = _action(table, uses[1:]) if uses.startswith("@") else uses
        if "with" in raw:
            out["with"] = {k: _subst(v, refs) if isinstance(v, str) else v for k, v in raw["with"].items()}
    else:
        out["run"] = _subst(raw["run"], refs)
        if "shell" in raw:
            out["shell"] = raw["shell"]
        if "dir" in raw:
            out["working-directory"] = raw["dir"]
    if "env" in raw:
        out["env"] = {k: _subst(v, refs) for k, v in raw["env"].items()}
    return out


def _upload(table: Table, name: str) -> dict:
    art = table.artifacts[name]
    with_: dict = {"name": _template(name), "path": art.path}
    if art.retention is not None:
        with_["retention-days"] = art.retention
    if art.if_no_files_found != "error":
        with_["if-no-files-found"] = art.if_no_files_found
    if art.compression is not None:
        with_["compression-level"] = art.compression
    return {"uses": _action(table, "upload-artifact"), "with": with_}


