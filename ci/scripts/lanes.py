def load(root: Path = REPO_ROOT) -> Table:
    return parse((root / TABLE).read_text(), root)


def refs(root: Path = REPO_ROOT) -> dict[str, str]:
    return ci_image.refs(root)


def check(root: Path = REPO_ROOT) -> list[str]:
    """Findings: a rendered file that differs from the table, or a workflow file
    the table does not render."""
    table = load(root)
    rendered = render_all(table, refs(root))
    findings = []
    for rel, text in rendered.items():
        path = root / rel
        if not path.exists():
            findings.append(f"{rel}: missing -- run `python3 ci/scripts/lanes.py render`")
        elif path.read_text() != text:
            findings.append(f"{rel}: differs from what ci/lanes.toml renders -- run `python3 ci/scripts/lanes.py render`")
    for path in sorted((root / WORKFLOWS_DIR).glob("*.y*ml")):
        rel = str(path.relative_to(root))
        if rel not in rendered:
            findings.append(f"{rel}: not rendered from ci/lanes.toml -- a workflow is a lane in the table")
    return findings


def render(root: Path = REPO_ROOT) -> list[str]:
    table = load(root)
    rendered = render_all(table, refs(root))
    for rel, text in rendered.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text)
    for path in sorted((root / WORKFLOWS_DIR).glob("*.y*ml")):
        if str(path.relative_to(root)) not in rendered:
            path.unlink()
    return sorted(rendered)


def run_lane(table: Table, lane_id: str, root: Path = REPO_ROOT) -> int:
    """Run a lane's `run` steps here, in order, with its environment; a lane
    whose steps use an action, or that needs a host this one is not, says so."""
    lane = table.lanes.get(lane_id)
    if lane is None:
        print(f"lanes: no lane `{lane_id}` ({', '.join(sorted(table.lanes))})", file=sys.stderr)
        return 2
    if lane.legs:
        print(f"lanes: `{lane_id}` has legs; run each leg's command by hand with its matrix values", file=sys.stderr)
    env = {**os.environ, **{k: v for k, v in lane.env.items() if "${{" not in v}}
    if "postgres" in lane.needs and "JAMMI_TEST_PG_URL" not in env:
        print("lanes: this lane needs Postgres: run it through `ci/dev.sh --with pg`", file=sys.stderr)
        return 2
    for step in lane.steps:
        if step.kind != "run":
            print(f"lanes: skipping a `{step.kind}` step ({step.raw.get(step.kind)}); only `run` steps run here", file=sys.stderr)
            continue
        cmd = step.raw["run"]
        if "${{" in cmd:
            print(f"lanes: a step carries a workflow expression and cannot run here:\n{cmd}", file=sys.stderr)
            return 2
        cwd = root / (step.raw.get("dir") or lane.dir or ".")
        print(f"==> {step.raw.get('name', cmd.splitlines()[0])}")
        proc = subprocess.run(["bash", "-e", "-o", "pipefail", "-c", cmd], cwd=cwd, env={**env, **step.raw.get("env", {})})
        if proc.returncode != 0:
            return proc.returncode
    return 0


def self_test() -> int:
    failures: list[str] = []

    def expect(label: str, text: str, want: str | None) -> None:
        try:
            parse(text)
            got = None
        except TableError as e:
            got = str(e)
        if (want is None) != (got is None) or (want and want not in (got or "")):
            failures.append(f"{label}: expected {want!r}, got {got!r}")

    base = """
    [workflow.ci]
    name = "CI"
    doc = "d"
    on = ["pr", "main"]
    [workflow.paid]
    name = "P"
    doc = "d"
    on = ["label:run-x", "dispatch"]
    [workflow.rel]
    name = "R"
    doc = "d"
    on = ["tag:v", "dispatch"]
    [action]
    checkout = "actions/checkout@0000000000000000000000000000000000000000 # v4"
    upload-artifact = "actions/upload-artifact@0000000000000000000000000000000000000000 # v4"
    download-artifact = "actions/download-artifact@0000000000000000000000000000000000000000 # v4"
    [artifact.a]
    path = "out"
    [lane.build]
    why = "Builds a."
    produces = ["a"]
    steps = [{run = "make"}]
    [lane.paid-ok]
    why = "Rents."
    workflow = "paid"
    needs = ["runpod"]
    steps = [{run = "x"}]
    [lane.rel-ok]
    why = "Promotes."
    workflow = "rel"
    when = ["tag:v"]
    publishes = "release"
    steps = [{run = "gh release upload"}]
    """
    expect("the base table parses", base, None)
    expect("a paid lane on a pull request", base + '\n[lane.p]\nwhy = "W."\nneeds = ["runpod"]\nsteps = [{run = "x"}]\n', "rents hardware")
    expect("a paid lane by label", base + '\n[lane.p]\nwhy = "W."\nworkflow = "paid"\nneeds = ["runpod"]\nsteps = [{run = "x"}]\n', None)
    expect("a publisher off a tag", base + '\n[lane.pub]\nwhy = "W."\nworkflow = "rel"\nsteps = [{run = "npm publish"}]\n', "declares no `publishes`")
    expect("a release lane on a dispatch", base + '\n[lane.pub]\nwhy = "W."\nworkflow = "rel"\npublishes = "release"\nsteps = [{run = "npm publish"}]\n', "never else")
    expect("a release lane that compiles", base + '\n[lane.pub]\nwhy = "W."\nworkflow = "rel"\nwhen = ["tag:v"]\npublishes = "release"\nsteps = [{run = "cargo build && npm publish"}]\n', "compiles nothing")
    expect("a release lane", base + '\n[lane.pub]\nwhy = "W."\nworkflow = "rel"\nwhen = ["tag:v"]\npublishes = "release"\nsteps = [{run = "npm publish"}]\n', None)
    expect("a secret outside a need", base + '\n[lane.s]\nwhy = "W."\nsteps = [{run = "x", env = {T = "${{ secrets.T }}"}}]\n', "secret outside a need")
    expect("an artifact nothing builds", base + '\n[lane.c]\nwhy = "W."\nconsumes = ["b"]\nsteps = [{run = "x"}]\n', "produced by no lane")
    expect("a wheel never held to the limit", base + '\n[lane.w]\nwhy = "W."\nsteps = [{run = "maturin build"}]\n', "per-file limit")
    expect("a release build spelling features", base + '\n[lane.w]\nwhy = "W."\nrust = "release"\nsteps = [{run = "cargo build --features cuda,mysql"}]\n', "spells features")
    expect("a release build reading the manifest", base + '\n[lane.w]\nwhy = "W."\nrust = "release"\nsteps = [{run = "cargo build --features \\"$FEATURES\\""}]\n', None)
    expect("an edge a lane never declared", base + '\n[lane.e]\nwhy = "W."\nsteps = [{run = "echo ${{ needs.build.outputs.x }}"}]\n', "not an edge")
    expect("a `when` the workflow lacks", base + '\n[lane.e]\nwhy = "W."\nwhen = ["schedule"]\nsteps = [{run = "x"}]\n', "names a trigger")
    expect("an unpinned action", base.replace("checkout@0000000000000000000000000000000000000000 # v4", "checkout@v4"), "40-hex sha")

    table = parse(base + '\n[lane.c]\nwhy = "W."\nhost = "ubuntu"\nconsumes = ["a"]\nsteps = [{download = "a", path = "in"}, {run = "ls"}]\n[lane.pub]\nwhy = "W."\nworkflow = "rel"\nhost = "ubuntu"\nwhen = ["tag:v"]\npublishes = "release"\nconsumes = ["a"]\nsteps = [{run = "npm publish"}]\n')
    fake_refs = {"cpu": "img:cpu", "cuda": "img:cuda", "postgres": "pg", "colab": "py"}
    ci = render_workflow(table, table.workflows["ci"], fake_refs)
    if ci["jobs"]["c"]["needs"] != ["build"] or ci["jobs"]["c"]["env"][ARTIFACT_RUN_ENV] != "${{ github.run_id }}":
        failures.append(f"an in-workflow consumer needs its producer and its own run: {ci['jobs']['c']}")
    if SUMMARY_LANE not in ci["jobs"] or ci["jobs"][SUMMARY_LANE]["needs"] != ["build", "c"]:
        failures.append("the merge-path workflow sums every job")
    rel = render_workflow(table, table.workflows["rel"], fake_refs)
    if set(rel["jobs"]["pub"]["needs"]) != {"artifacts-ci", PROOF_LANE} or rel["jobs"]["pub"]["if"] != "startsWith(github.ref, 'refs/tags/v')":
        failures.append(f"a release lane waits on the proof and the proving run: {rel['jobs']['pub']}")
    if "always()" in str(rel["jobs"]["pub"]):
        failures.append("a release lane never carries always()")
    text = emit(dict(rel))
    if "${{ secrets." in text:
        failures.append("a rendered release workflow reads no secret")
    for v, want in (("3.12", "'3.12'"), ("*/6", "'*/6'"), ("a: b", "'a: b'"), ("${{ x }}", "${{ x }}"), ("on", "'on'"), ("plain text", "plain text"), ("--flag", "'--flag'")):
        if _scalar(v) != want:
            failures.append(f"emit {v!r} as {want!r}, got {_scalar(v)!r}")
    if failures:
        print("lanes self-test: FAIL", file=sys.stderr)
        for f in failures:
            print(f"  - {f}", file=sys.stderr)
        return 1
    print("lanes self-test: OK")
    return 0


def main(argv: list[str]) -> int:
    if argv == ["--self-test"]:
        return self_test()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command", required=True)
    sub.add_parser("render")
    sub.add_parser("check")
    ls = sub.add_parser("list")
    ls.add_argument("workflow", nargs="?")
    rn = sub.add_parser("run")
    rn.add_argument("lane")
    args = ap.parse_args(argv)
    try:
        if args.command == "render":
            for rel in render():
                print(rel)
            return 0
        if args.command == "check":
            findings = check()
            for f in findings:
                print(f"::error::lanes: {f}", file=sys.stderr)
            if not findings:
                print("lanes: every workflow is what ci/lanes.toml renders")
            return 1 if findings else 0
        table = load()
        if args.command == "list":
            for wf in table.workflows.values():
                if args.workflow and wf.id != args.workflow:
                    continue
                print(f"{wf.file}:")
                for lane in table.in_workflow(wf.id):
                    print(f"  {lane.id:28} {lane.host:10} {', '.join(lane.needs)}")
            return 0
        return run_lane(table, args.lane)
    except TableError as e:
        print(f"::error::lanes: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
